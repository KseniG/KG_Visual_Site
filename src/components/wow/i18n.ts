const DICT: Record<Lang, Dict> = { ru, kk, en, de, fr, it, es };

/** Язык сайта по <html lang>: «ru-RU» → ru; незнакомый — en. */
export function siteLang(): Lang {
  const raw = (typeof document !== "undefined" ? document.documentElement.lang : "ru").toLowerCase().slice(0, 2);
  return (LANGS as readonly string[]).includes(raw) ? (raw as Lang) : "en";
}

/** Локаль для Intl (даты, числа): ru-RU, kk-KZ, en-GB, de-DE, fr-FR, it-IT, es-ES; можно уточнить пропсом. */
export const LOCALES: Record<Lang, string> = { ru: "ru-RU", kk: "kk-KZ", en: "en-GB", de: "de-DE", fr: "fr-FR", it: "it-IT", es: "es-ES" };

export type Labels = Partial<Record<Key, string>>;

/** t("today") → «Сегодня» на языке сайта; labels — свои надписи блока поверх словаря. */
export function useT(labels?: Labels) {
  return useMemo(() => {
    const lang = siteLang();
    const dict = DICT[lang];
    const t = (key: Key, vars?: Record<string, string | number>) => {
      let s = labels?.[key] ?? dict[key] ?? ru[key];
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      return s;
    };
    return { t, lang, locale: LOCALES[lang] };
  }, [labels]);
}

/** Сумма с валютой на языке сайта: money(5000, "RUB", "ru-RU") → «5 000 ₽». Для kk — правила ru-RU (те же пробелы;
 *  в части браузеров нет данных kk): 5000 KZT → «5 000 ₸». */
export function money(n: number, currency: string, locale: string) {
  const loc = locale.toLowerCase().startsWith("kk") ? "ru-RU" : locale;
  // разряды — всегда: по-итальянски и по-испански Intl иначе пишет «5900 €» без точки
  const opts = { style: "currency", currency, currencyDisplay: "narrowSymbol", maximumFractionDigits: 0, useGrouping: "always" } as Intl.NumberFormatOptions;
  return new Intl.NumberFormat(loc, opts).format(Math.round(n));
}
